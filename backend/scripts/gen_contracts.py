"""계약 생성 파이프라인 (WP0-A).

원본: ``contracts/schemas/**/*.json`` (JSON Schema 2020-12) + ``contracts/openapi.yaml``
     + ``contracts/examples/*.json`` (OpenAPI Example Object).
생성물(커밋한다):
  1. ``contracts/openapi.bundled.yaml`` — 외부 $ref 없는 자립 번들. 프론트 타입 생성
     (openapi-typescript)과 MSW 핸들러는 이것을 쓴다.
  2. ``backend/app/core/contracts_gen.py`` — 번들의 components.schemas 전부를
     datamodel-code-generator로 만든 pydantic v2 모델.

사용법 (backend/ 에서)::

    uv run python scripts/gen_contracts.py          # 생성물 갱신
    uv run python scripts/gen_contracts.py --check  # 생성물이 원본과 다르면 exit 1

번들 규칙
- 스키마 파일 하나 = component 하나. 이름은 파일의 ``title``.
- 파일 안의 ``$defs`` 는 component로 끌어올린다. 이름은 각 정의의 ``title``(없으면 키).
  모든 component 이름은 전역에서 유일해야 한다(충돌하면 실패).
- ``$ref``: 'x.json' → '#/components/schemas/<X title>', 'x.json#/$defs/Y' 와 '#/$defs/Y'
  → '#/components/schemas/<Y title>'.
- ``$id`` · ``$schema`` 는 번들에서 지운다(3.1에서 $id가 base URI를 바꾸기 때문).
- openapi.yaml 의 example ``$ref: ./examples/x.json`` 은 내용으로 치환한다.
"""

from __future__ import annotations

import argparse
import copy
import difflib
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

import yaml

BACKEND_DIR = Path(__file__).resolve().parents[1]
REPO_DIR = BACKEND_DIR.parent
CONTRACTS_DIR = REPO_DIR / "contracts"
SCHEMAS_DIR = CONTRACTS_DIR / "schemas"
OPENAPI_SRC = CONTRACTS_DIR / "openapi.yaml"
OPENAPI_BUNDLED = CONTRACTS_DIR / "openapi.bundled.yaml"
CONTRACTS_GEN = BACKEND_DIR / "app" / "core" / "contracts_gen.py"

BUNDLE_HEADER = (
    "# GENERATED by backend/scripts/gen_contracts.py from contracts/openapi.yaml + contracts/schemas/.\n"
    "# 손으로 고치지 않는다. 원본을 고치고 `uv run python scripts/gen_contracts.py` 를 다시 돌린다.\n"
)
MODELS_HEADER = (
    '"""GENERATED by backend/scripts/gen_contracts.py (datamodel-code-generator, pydantic v2).\n\n'
    "원본: contracts/schemas/**/*.json → contracts/openapi.bundled.yaml. 손으로 고치지 않는다.\n"
    '"""\n'
    "\n"
    "# ruff: noqa: E501  (docstring은 스키마 description을 그대로 옮긴다)\n"
)

Json = Any


class BundleError(RuntimeError):
    pass


def _load_json(path: Path) -> Json:
    with path.open(encoding="utf-8") as f:
        return json.load(f)


def schema_files() -> list[Path]:
    return sorted(p for p in SCHEMAS_DIR.rglob("*.json") if p.is_file())


def _rel(path: Path) -> str:
    return path.relative_to(SCHEMAS_DIR).as_posix()


class Bundler:
    """schemas/ 를 읽어 component 이름표를 만들고 $ref를 다시 쓴다."""

    def __init__(self) -> None:
        self.docs: dict[str, Json] = {rel: _load_json(SCHEMAS_DIR / rel) for rel in map(_rel, schema_files())}
        # (file rel, def key or None) -> component name
        self.names: dict[tuple[str, str | None], str] = {}
        owners: dict[str, str] = {}
        for rel, doc in self.docs.items():
            title = doc.get("title")
            if not isinstance(title, str) or not title:
                raise BundleError(f"{rel}: top-level 'title' is required")
            self._claim(owners, title, rel)
            self.names[(rel, None)] = title
            for key, sub in (doc.get("$defs") or {}).items():
                name = sub.get("title") or key
                self._claim(owners, name, f"{rel}#/$defs/{key}")
                self.names[(rel, key)] = name

    @staticmethod
    def _claim(owners: dict[str, str], name: str, where: str) -> None:
        if name in owners:
            raise BundleError(f"component name {name!r} defined twice: {owners[name]} and {where}")
        owners[name] = where

    def _resolve_ref(self, ref: str, base_rel: str) -> str:
        if ref.startswith("#/components/"):
            return ref
        target, _, fragment = ref.partition("#")
        if target:
            base_dir = Path(base_rel).parent
            rel = (base_dir / target).as_posix()
            rel = os.path.normpath(rel).replace("\\", "/")
        else:
            rel = base_rel
        if rel not in self.docs:
            raise BundleError(f"{base_rel}: unresolved $ref {ref!r}")
        if fragment in ("", "/"):
            return f"#/components/schemas/{self.names[(rel, None)]}"
        prefix = "/$defs/"
        if not fragment.startswith(prefix) or "/" in fragment[len(prefix) :]:
            raise BundleError(f"{base_rel}: only whole-file or top-level $defs refs are allowed, got {ref!r}")
        key = fragment[len(prefix) :]
        if (rel, key) not in self.names:
            raise BundleError(f"{base_rel}: unresolved $ref {ref!r}")
        return f"#/components/schemas/{self.names[(rel, key)]}"

    def _rewrite(self, node: Json, base_rel: str) -> Json:
        if isinstance(node, dict):
            out: dict[str, Json] = {}
            for k, v in node.items():
                if k in ("$id", "$schema", "$defs"):
                    continue
                if k == "$ref" and isinstance(v, str):
                    out[k] = self._resolve_ref(v, base_rel)
                elif k in ("examples", "default", "const", "enum"):
                    out[k] = copy.deepcopy(v)
                else:
                    out[k] = self._rewrite(v, base_rel)
            return out
        if isinstance(node, list):
            return [self._rewrite(v, base_rel) for v in node]
        return node

    def components(self) -> dict[str, Json]:
        comps: dict[str, Json] = {}
        for rel, doc in self.docs.items():
            comps[self.names[(rel, None)]] = self._rewrite(doc, rel)
            for key, sub in (doc.get("$defs") or {}).items():
                comps[self.names[(rel, key)]] = self._rewrite(sub, rel)
        return comps

    def ref_for_file(self, file_ref: str) -> str:
        """openapi.yaml 의 './schemas/x.json' → component 이름."""
        rel = file_ref.removeprefix("./").removeprefix("schemas/")
        target, _, fragment = rel.partition("#")
        if target not in self.docs:
            raise BundleError(f"openapi.yaml: unknown schema file {file_ref!r}")
        if fragment:
            return self._resolve_ref(f"{target}#{fragment}", target).rsplit("/", 1)[1]
        return self.names[(target, None)]


def _inline_examples(node: Json) -> Json:
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and ref.startswith("./examples/"):
            data = _load_json(CONTRACTS_DIR / ref.removeprefix("./"))
            if not isinstance(data, dict) or "value" not in data:
                raise BundleError(f"{ref}: example file must be an OpenAPI Example Object with 'value'")
            return data
        return {k: _inline_examples(v) for k, v in node.items()}
    if isinstance(node, list):
        return [_inline_examples(v) for v in node]
    return node


def _rewrite_openapi_refs(node: Json, bundler: Bundler) -> Json:
    if isinstance(node, dict):
        out: dict[str, Json] = {}
        for k, v in node.items():
            if (
                k == "$ref"
                and isinstance(v, str)
                and (v.startswith("./schemas/") or v.startswith("schemas/"))
            ):
                out[k] = f"#/components/schemas/{bundler.ref_for_file(v)}"
            elif k in ("example", "examples") and not isinstance(v, dict):
                out[k] = copy.deepcopy(v)
            else:
                out[k] = _rewrite_openapi_refs(v, bundler)
        return out
    if isinstance(node, list):
        return [_rewrite_openapi_refs(v, bundler) for v in node]
    return node


def build_bundle() -> dict[str, Json]:
    bundler = Bundler()
    with OPENAPI_SRC.open(encoding="utf-8") as f:
        src = yaml.safe_load(f)
    doc = _inline_examples(src)
    comps = doc.setdefault("components", {})
    src_schemas: dict[str, Json] = comps.get("schemas") or {}
    file_comps = bundler.components()
    merged: dict[str, Json] = {}
    # openapi.yaml 의 components.schemas 는 파일 $ref 별칭이거나 인라인 스키마다.
    for name, schema in src_schemas.items():
        if isinstance(schema, dict) and set(schema) == {"$ref"} and not schema["$ref"].startswith("#"):
            target = bundler.ref_for_file(schema["$ref"])
            if target != name:
                raise BundleError(f"components.schemas.{name} must be named after the file title {target!r}")
            continue
        if name in file_comps:
            raise BundleError(f"components.schemas.{name} collides with a schema file title")
        merged[name] = schema
    doc = _rewrite_openapi_refs(doc, bundler)
    inline = doc["components"].get("schemas") or {}
    all_schemas: dict[str, Json] = {}
    for name in sorted(file_comps):
        all_schemas[name] = file_comps[name]
    for name in sorted(merged):
        all_schemas[name] = inline[name]
    doc["components"]["schemas"] = all_schemas
    _assert_no_external_refs(doc)
    return doc


def _assert_no_external_refs(node: Json, path: str = "$") -> None:
    if isinstance(node, dict):
        ref = node.get("$ref")
        if isinstance(ref, str) and not ref.startswith("#/"):
            raise BundleError(f"external $ref left in bundle at {path}: {ref}")
        for k, v in node.items():
            _assert_no_external_refs(v, f"{path}.{k}")
    elif isinstance(node, list):
        for i, v in enumerate(node):
            _assert_no_external_refs(v, f"{path}[{i}]")


class _Dumper(yaml.SafeDumper):
    pass


def _str_presenter(dumper: yaml.SafeDumper, data: str) -> yaml.ScalarNode:
    if "\n" in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style="|")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


_Dumper.add_representer(str, _str_presenter)


def render_bundle(doc: dict[str, Json]) -> str:
    body = yaml.dump(doc, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=4096)
    return BUNDLE_HEADER + body


def render_models(bundle_text: str) -> str:
    with tempfile.TemporaryDirectory() as tmp:
        src = Path(tmp) / "openapi.bundled.yaml"
        out = Path(tmp) / "contracts_gen.py"
        src.write_text(bundle_text, encoding="utf-8", newline="\n")
        cmd = [
            sys.executable,
            "-m",
            "datamodel_code_generator",
            "--input", str(src),
            "--input-file-type", "openapi",
            "--openapi-scopes", "schemas",
            "--output", str(out),
            "--output-model-type", "pydantic_v2.BaseModel",
            "--target-python-version", "3.12",
            "--use-standard-collections",
            "--use-union-operator",
            "--use-annotated",
            "--field-constraints",
            "--enum-field-as-literal", "all",
            "--use-title-as-name",
            "--collapse-root-models",
            "--type-mappings", "string+date=string", "string+date-time=string", "string+uri=string",
            "--use-schema-description",
            "--use-field-description",
            "--use-double-quotes",
            "--disable-timestamp",
            "--keep-model-order",
            "--formatters", "ruff-format",
        ]  # fmt: skip
        env = dict(os.environ, PYTHONUTF8="1")
        proc = subprocess.run(cmd, capture_output=True, text=True, encoding="utf-8", env=env, check=False)
        if proc.returncode != 0:
            raise BundleError(f"datamodel-codegen failed:\n{proc.stdout}\n{proc.stderr}")
        code = out.read_text(encoding="utf-8")
    lines = code.splitlines()
    # datamodel-codegen 헤더(파일명 주석)를 고정 헤더로 바꾼다 — 임시 경로가 들어가면 재생성 diff가 생긴다.
    while lines and lines[0].startswith("#"):
        lines.pop(0)
    body = "\n".join(lines).strip("\n") + "\n"
    return _ruff_fix(MODELS_HEADER + "\n" + body)


def _ruff_fix(code: str) -> str:
    with tempfile.TemporaryDirectory() as tmp:
        path = Path(tmp) / "contracts_gen.py"
        path.write_text(code, encoding="utf-8", newline="\n")
        cfg = ["--config", str(BACKEND_DIR / "pyproject.toml")]
        for args in (["check", "--fix-only", "--exit-zero", "--quiet"], ["format", "--quiet"]):
            subprocess.run(
                [sys.executable, "-m", "ruff", *args, *cfg, str(path)],
                check=True,
                capture_output=True,
            )
        return path.read_text(encoding="utf-8")


def outputs() -> dict[Path, str]:
    bundle_text = render_bundle(build_bundle())
    return {OPENAPI_BUNDLED: bundle_text, CONTRACTS_GEN: render_models(bundle_text)}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--check", action="store_true", help="생성물이 최신인지 검사만 한다")
    args = parser.parse_args(argv)
    results = outputs()
    stale = []
    for path, text in results.items():
        current = path.read_text(encoding="utf-8") if path.exists() else ""
        if current != text:
            stale.append(path)
            if args.check:
                diff = difflib.unified_diff(
                    current.splitlines(), text.splitlines(), str(path), "regenerated", lineterm="", n=1
                )
                sys.stdout.write("\n".join(list(diff)[:60]) + "\n")
            else:
                path.write_text(text, encoding="utf-8", newline="\n")
    if args.check and stale:
        print("stale generated files:", ", ".join(str(p.relative_to(REPO_DIR)) for p in stale))
        return 1
    if not args.check:
        for path in results:
            print(("updated " if path in stale else "unchanged ") + str(path.relative_to(REPO_DIR)))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

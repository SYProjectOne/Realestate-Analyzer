def _call(text: str) -> Any:
    from app.normalize.notice_parser import TypeSpec, _discount_line

    return _discount_line(text, TypeSpec(short=SHORT, long=LONG, area_text="84.9582", units=10, span=(0, 1)))


def _labels(text: str) -> list[str]:
    """공고문 파서 경로의 84A 할인 후보 라벨들(픽스처 공고 뒤에 붙인다)."""
    return [
        label or "" for f, _v, label, _r in _disc(_base() + "\n" + text + "\n") if f == "discount_by_type.84A"
    ]



/**
 * npm run gen:api — openapi → src/api/schema.d.ts (openapi-typescript).
 * 입력 선택은 scripts/lib/openapi-source.ts (openapi.config.json 한 줄).
 */
import { writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { FRONTEND_ROOT, resolveOpenapiSource } from './lib/openapi-source';

const OUTPUT = resolve(FRONTEND_ROOT, 'src/api/schema.d.ts');

async function main(): Promise<void> {
  const source = resolveOpenapiSource();
  // defaultNonNullable: false — `default`가 있는 선택 필드(Fact.human 등)를 필수로 만들지 않는다.
  // 응답 예시에 그 필드가 없으므로 필수로 만들면 생성 타입이 실제 응답과 어긋난다(계약 2026-10-09.2).
  const ast = await openapiTS(pathToFileURL(source.path), { defaultNonNullable: false });
  const header = [
    '/**',
    ` * AUTO-GENERATED by \`npm run gen:api\` from ${source.display} (${source.mode}).`,
    ' * 손으로 고치지 않는다 — 다음 생성에 사라진다. 원본은 contracts/openapi.yaml.',
    ' */',
    '',
  ].join('\n');
  writeFileSync(OUTPUT, header + astToString(ast), 'utf8');
  console.log(`gen:api  ${source.display} → src/api/schema.d.ts`);
}

main().catch((err: unknown) => {
  console.error(err instanceof Error ? err.message : err);
  process.exit(1);
});

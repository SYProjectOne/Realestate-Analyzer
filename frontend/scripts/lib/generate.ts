/**
 * 생성물 만들기(파일 쓰기 없음) — gen:api·gen:msw 와 최신성 테스트(scripts/generated.fresh.test.ts)가 같은 코드를 쓴다.
 */
import { readFileSync } from 'node:fs';
import { pathToFileURL } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';
import { parse } from 'yaml';
import { generateMswHandlers, type CodegenResult } from './msw-codegen';
import type { OpenapiSource } from './openapi-source';

/** openapi → src/api/schema.d.ts 내용 */
export async function generateSchemaTypes(source: OpenapiSource): Promise<string> {
  // defaultNonNullable: false — `default`가 있는 선택 필드(Fact.human 등)를 필수로 만들지 않는다.
  // 응답 예시에 그 필드가 없으므로 필수로 만들면 생성 타입이 실제 응답과 어긋난다(계약 2026-10-09.2).
  const ast = await openapiTS(pathToFileURL(source.path), { defaultNonNullable: false });
  const header = [
    '/**',
    ` * AUTO-GENERATED by \`npm run gen:api\` from ${source.display} (${source.mode}).`,
    ' * 손으로 고치지 않는다 — 다음 생성에 사라진다. 원본은 contracts/openapi.yaml.',
    ' */',
    '',
  ].join('\n');
  return header + astToString(ast);
}

/** openapi 의 response example(s) → src/mocks/handlers.gen.ts 내용 */
export function generateMswSource(source: OpenapiSource): CodegenResult {
  const doc = parse(readFileSync(source.path, 'utf8'), { maxAliasCount: -1 }) as Record<
    string,
    unknown
  >;
  return generateMswHandlers(doc, `${source.display} (${source.mode})`);
}
